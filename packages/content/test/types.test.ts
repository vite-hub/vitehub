import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises"
import { tmpdir } from "node:os"
import { dirname, join } from "node:path"
import { setTimeout as delay } from "node:timers/promises"
import { afterEach, expect, it, vi } from "vitest"

import { contentSource, defineContent, defineContentTypesPlugin, generateContentTypes } from "../src/index.ts"

const directories: string[] = []
afterEach(async () => {
  await Promise.all(directories.splice(0).map(directory => rm(directory, { force: true, recursive: true })))
})

function writeTypes(file: string) {
  return async (declarations: string) => {
    await mkdir(dirname(file), { recursive: true })
    await writeFile(file, declarations, "utf8")
  }
}

function docs(items: Array<{ key: string, content: string }>) {
  return { async items() { return items } }
}

function deferred() {
  let resolve!: () => void
  const promise = new Promise<void>((resolvePromise) => {
    resolve = resolvePromise
  })
  return { promise, resolve }
}

it("types every Source by name and by document path", async () => {
  const content = defineContent({
    access: "public",
    sources: {
      docs: docs([{ key: "about.md", content: "---\ntitle: About\norder: 2\n---\n# About\n" }]),
      blog: docs([{ key: "hello.md", content: "---\ntitle: Hello\ndraft: true\n---\n# Hello\n" }]),
    },
  })

  const declarations = await generateContentTypes(content, { moduleName: "vite-hub/content" })

  expect(declarations).toContain("// Generated by ViteHub with comark-content")
  expect(declarations).toContain("declare module 'vite-hub/content'")
  expect(declarations).toMatch(/interface DocsData \{[^}]*title: string[^}]*order: number/s)
  expect(declarations).toMatch(/interface BlogData \{[^}]*draft: boolean/s)
  expect(declarations).toContain("'docs': { data: DocsData; row: DocsRow }")
  expect(declarations).toContain("'/about': DocsData")
  expect(declarations).toContain("'/hello': BlogData")
})

it("writes JSON Schema integers as numbers", async () => {
  const schema = {
    type: "object",
    properties: { size: { type: "integer" }, sizes: { type: "array", items: { type: ["integer", "null"] } } },
    required: ["size"],
  }
  const content = defineContent({ access: "public", sources: { media: contentSource(docs([{ key: "a.md", content: "---\nsize: 1\n---\n" }]), { schema }) } })

  const declarations = await generateContentTypes(content)

  expect(declarations).toMatch(/size: number;/)
  expect(declarations).toMatch(/sizes\?: Array<number \| null>;/)
  expect(declarations).not.toContain("integer")
})

it("writes the types in the background and again after Content changes", async () => {
  const directory = await mkdtemp(join(tmpdir(), "vitehub-content-types-"))
  directories.push(directory)
  const file = join(directory, "types/content.d.ts")
  const items = [{ key: "about.md", content: "---\ntitle: About\n---\n# About\n" }]
  const content = defineContent({ access: "public", sources: { docs: docs(items) } })

  defineContentTypesPlugin(async () => content, writeTypes(file))()
  await expect.poll(async () => await readFile(file, "utf8").catch(() => ""), { timeout: 5_000 }).toContain("'/about': DocsData")

  items.push({ key: "guide.md", content: "---\ntitle: Guide\n---\n# Guide\n" })
  await content.cache.refresh("docs")
  await expect.poll(async () => await readFile(file, "utf8"), { timeout: 5_000 }).toContain("'/guide': DocsData")
})

it("reports a Source that fails to load once and keeps the server running", async () => {
  const directory = await mkdtemp(join(tmpdir(), "vitehub-content-types-"))
  directories.push(directory)
  const warnings: unknown[] = []
  const warn = console.warn
  console.warn = (...args: unknown[]) => void warnings.push(args.join(" "))
  try {
    defineContentTypesPlugin(async () => { throw new Error("broken content module") }, writeTypes(join(directory, "content.d.ts")))()
    await expect.poll(() => warnings.length, { timeout: 5_000 }).toBe(1)
    await delay(50)
    expect(warnings).toEqual(["[vitehub] Could not generate Content types: broken content module"])
  }
  finally {
    console.warn = warn
  }
})

it("keeps changes received after a generation has read the Source", async () => {
  const directory = await mkdtemp(join(tmpdir(), "vitehub-content-types-"))
  directories.push(directory)
  const file = join(directory, "content.d.ts")
  const items = [{ key: "about.md", content: "---\ntitle: About\n---\n" }]
  const started = deferred()
  const resume = deferred()
  const content = defineContent({ access: "public", sources: {
    docs: docs(items),
    blog: { async items() {
      started.resolve()
      await resume.promise
      return [{ key: "hello.md", content: "---\ntitle: Hello\n---\n" }]
    } },
  } })
  const write = vi.fn(writeTypes(file))
  defineContentTypesPlugin(async () => content, write)()
  await started.promise
  try {
    items.push({ key: "guide.md", content: "---\ntitle: Guide\n---\n" })
    await content.cache.refresh("docs")
  }
  finally {
    resume.resolve()
  }
  await expect.poll(async () => await readFile(file, "utf8").catch(() => ""), { timeout: 2_000 }).toContain("'/guide': DocsData")
  await delay(650)
  expect(write).toHaveBeenCalledTimes(2)
})
