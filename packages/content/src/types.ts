import { generateSourceTypes } from "comark-content"

import type { ComarkContent, ContentHooks, TypegenFieldContext } from "comark-content"

/** The Content runtime parts that type generation reads. */
export interface ContentTypesHost {
  readonly instances: readonly ComarkContent[]
}

export interface ContentTypesOptions {
  /** The module that re-exports Comark's registry interfaces, such as `@vite-hub/content` or `vite-hub/content`. */
  moduleName?: string
}

/**
 * The declarations that type `content.get()`, `content.list()`, and `content.query()` from the schema of every
 * Content source and collection. Comark infers a Source's schema from its documents. A collection uses its fields.
 */
export async function generateContentTypes(content: ContentTypesHost, options: ContentTypesOptions = {}): Promise<string> {
  return generateTypes(content, options)
}

async function generateTypes(content: ContentTypesHost, options: ContentTypesOptions, currentState = false): Promise<string> {
  for (const instance of content.instances) {
    if (typedInstances.has(instance)) continue
    typedInstances.add(instance)
    instance.hooks.hook("typegen:field", integerAsNumber)
  }
  // The watcher reads live Content state. Comark's forced init would emit bulk-load events on every pass.
  const instances = currentState
    ? content.instances.map(instance => ({ ...instance, init: () => instance.init() }))
    : [...content.instances]
  const declarations = await generateSourceTypes(instances, { moduleName: options.moduleName ?? "@vite-hub/content" })
  return declarations.replace(/^\/\/ Generated by comark-content.*$/m, "// Generated by ViteHub with comark-content. Do not edit this file.")
}

const typedInstances = new WeakSet<ComarkContent>()

/** Comark writes JSON Schema's `integer`, from a field such as `z.number().int()`, as a TypeScript type name. */
function integerAsNumber(field: TypegenFieldContext): void {
  if (![field.schema.type].flat().includes("integer")) return
  field.type = field.type.split(" | ").map(part => part === "integer" ? "number" : part).join(" | ")
}

const regenerateEvents = ["file:bulk:load", "file:upsert", "file:remove"] as const satisfies ReadonlyArray<keyof ContentHooks>

/**
 * A Nitro plugin for development that sends Content types to the host through `write` when the server starts, and again after
 * Content changes. `load` returns the Content runtime of `server/content.ts`. ViteHub generates the plugin in
 * `.vitehub/content/types.mjs`. Generation reads every Source and the `published` ref of every collection, so it runs
 * in the background and never delays a request.
 */
export function defineContentTypesPlugin(load: () => Promise<ContentTypesHost>, write: (declarations: string) => Promise<void>, options: ContentTypesOptions = {}): () => void {
  return () => {
    let content: ContentTypesHost | undefined
    let generating = false
    let pending = false
    let timer: ReturnType<typeof setTimeout> | undefined
    let warned = false

    async function generate(): Promise<void> {
      generating = true
      try {
        if (!content) {
          content = await load()
          for (const instance of content.instances) {
            for (const event of regenerateEvents) instance.hooks.hook(event, () => schedule(500))
          }
        }
        const declarations = await generateTypes(content, options, true)
        await write(declarations)
      }
      catch (error) {
        // Types are a development aid. A Source that fails to load reports its own error when the app reads it.
        if (!warned) console.warn(`[vitehub] Could not generate Content types: ${error instanceof Error ? error.message : String(error)}`)
        warned = true
      }
      finally {
        generating = false
        if (pending) {
          pending = false
          schedule(500)
        }
      }
    }

    function schedule(delay: number): void {
      if (generating) {
        pending = true
        return
      }
      clearTimeout(timer)
      timer = setTimeout(() => void generate(), delay)
    }

    schedule(0)
  }
}
