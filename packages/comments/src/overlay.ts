/** Which pages get the overlay. Globs are relative to the app base: `*` is one path segment and `**` any depth. */
export interface CommentsOverlayOptions {
  /** Pages that get the overlay. Default: every page. */
  paths?: string[]
  /** Pages that never get it. */
  exclude?: string[]
}

/** The prebuilt loader and overlay, and the version that keys their URLs. `vite-hub` supplies them. */
export interface CommentsOverlayAssets {
  /** Directory with `loader.js` and `overlay.js`. */
  dir: string
  /** Changes with the content of the bundle, so a long cache never serves an old one. */
  version: string
}

/** Where the loader and overlay are served, below the app mount. */
export const overlayRoute = "/_vitehub/comments"

/** The path the app is mounted at: `""` for the root, `"/portal"` below it. A relative or empty Vite base is the root. */
export function mountPath(base: string | undefined): string {
  if (!base || base === "./") return ""
  let pathname = base
  if (/^https?:\/\//.test(pathname)) {
    try {
      pathname = new URL(pathname).pathname
    }
    catch {
      return ""
    }
  }
  if (!pathname.startsWith("/") || pathname.startsWith("//")) return ""
  return pathname.replace(/\/+$/, "")
}

/** The URL of the loader, with the version and the page filter in its query. */
export function loaderUrl(mount: string, assets: Pick<CommentsOverlayAssets, "version">, options: CommentsOverlayOptions = {}): string {
  const filter = options.paths?.length || options.exclude?.length
    ? `&o=${encodeURIComponent(JSON.stringify({ exclude: options.exclude ?? [], paths: options.paths ?? [] }))}`
    : ""
  return `${mount}${overlayRoute}/loader.js?v=${encodeURIComponent(assets.version)}${filter}`
}

export function loaderTag(url: string): string {
  return `<script type="module" src="${url.replaceAll("&", "&amp;").replaceAll('"', "&quot;")}"></script>`
}

/** Puts the tag before `</body>`, or at the end. A page that has the loader already stays as it is. */
export function injectLoader(html: string, tag: string): string {
  if (html.includes(`${overlayRoute}/loader.js`)) return html
  const close = html.search(/<\/body\s*>(?![\s\S]*<\/body\s*>)/i)
  return close === -1 ? `${html}${tag}` : `${html.slice(0, close)}${tag}${html.slice(close)}`
}

/**
 * Source of the Nitro middleware that adds the loader to HTML responses: server-rendered pages and, when Nitro
 * prerenders them, the saved files. It is Nitro 3 middleware `(event, next)`. Where the host calls it without `next`,
 * such as Nitro 2 under Nuxt, it does nothing, and the `render:html` hook of the runtime plugin does the work.
 */
export function renderOverlayMiddleware(tag: string): string {
  return [
    "// Generated by @vite-hub/comments. Do not edit.",
    `const tag = ${JSON.stringify(tag)}`,
    `const marker = ${JSON.stringify(`${overlayRoute}/loader.js`)}`,
    "",
    "function inject(html) {",
    "  if (html.includes(marker)) return html",
    "  const close = html.search(/<\\/body\\s*>(?![\\s\\S]*<\\/body\\s*>)/i)",
    "  return close === -1 ? html + tag : html.slice(0, close) + tag + html.slice(close)",
    "}",
    "",
    "export default async function injectCommentsLoader(event, next) {",
    "  if (typeof next !== \"function\") return",
    "  const result = await next()",
    "  try {",
    "    const url = new URL(event.req.url)",
    "    if (event.req.method !== \"GET\" || /\\/_vitehub(\\/|$)/.test(url.pathname)) return result",
    "    if (result instanceof Response) {",
    "      if (!(result.headers.get(\"content-type\") ?? \"\").includes(\"text/html\")) return result",
    "      const headers = new Headers(result.headers)",
    "      headers.delete(\"content-length\")",
    "      return new Response(inject(await result.text()), { headers, status: result.status, statusText: result.statusText })",
    "    }",
    "    if (typeof result === \"string\" && ((event.res.headers.get(\"content-type\") ?? \"\").includes(\"text/html\") || /<\\/body\\s*>/i.test(result))) return inject(result)",
    "  }",
    "  catch {",
    "    // A page without the overlay is better than a failed page.",
    "  }",
    "  return result",
    "}",
    "",
  ].join("\n")
}
