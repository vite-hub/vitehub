/** Path helpers of the target OS, so a fake Windows host gives Windows paths on Linux. */
export function pathsFor(platform: OsSchedulePlatform): typeof posix {
  return platform === "win32" ? win32 : posix
}

/** Trims command output for an error, keeping the end. */
export function commandOutput(result: ExecResult): string {
  const output = `${result.stderr.trim()}\n${result.stdout.trim()}`.trim()
  return output.length > 2000 ? `…${output.slice(-2000)}` : output
}

function exec(file: string, args: readonly string[], env?: Record<string, string>): Promise<ExecResult> {
  return new Promise((resolve) => {
    execFile(file, args, { encoding: "utf8", env: env ? { ...process.env, ...env } : process.env, maxBuffer: 16 * 1024 * 1024, windowsHide: true }, (error, stdout, stderr) => {
      if (!error) return resolve({ code: 0, stdout, stderr })
      // A missing program has a string code, such as "ENOENT", and no exit code.
      const code = typeof error.code === "number" ? error.code : 127
      resolve({ code, stdout, stderr: stderr || error.message })
    })
  })
}

function isMissing(error: unknown): boolean {
  return error instanceof Error && "code" in error && (error.code === "ENOENT" || error.code === "ENOTDIR")
}

async function resolvePath(path: string): Promise<string> {
  try {
    return await realpath(path)
  }
  catch (error) {
    if (!isMissing(error)) throw error
    if (dirname(path) === path) return path
    return join(await resolvePath(dirname(path)), basename(path))
  }
}

export function createNodeHost(): OsHost {
  const user = userInfo().username
  return {
    platform: process.platform,
    uid: process.getuid?.(),
    user: process.platform === "win32" && process.env.USERDOMAIN ? `${process.env.USERDOMAIN}\\${user}` : user,
    // Read on each call, so a change of HOME or TZ in the process applies to the next call.
    get homedir() {
      return homedir()
    },
    env: process.env,
    get machineTimeZone() {
      return Intl.DateTimeFormat().resolvedOptions().timeZone
    },
    now: () => new Date(),
    sleep: ms => new Promise(resolve => setTimeout(resolve, ms)),
    exec,
    fs: {
      async readFile(path) {
        try {
          return await readFile(path, "utf8")
        }
        catch (error) {
          if (isMissing(error)) return undefined
          throw error
        }
      },
      async writeFile(path, content) {
        await mkdir(dirname(path), { recursive: true })
        await writeFile(path, content, { encoding: "utf8", mode: 0o644 })
      },
      async mkdir(path) {
        await mkdir(path, { recursive: true })
      },
      async rm(path) {
        try {
          await rm(path)
          return true
        }
        catch (error) {
          if (isMissing(error)) return false
          throw error
        }
      },
      async rmdirIfEmpty(path) {
        try {
          await rmdir(path)
        }
        catch (error) {
          if (isMissing(error) || (error instanceof Error && "code" in error && (error.code === "ENOTEMPTY" || error.code === "EEXIST"))) return
          throw error
        }
      },
      realpath: resolvePath,
    },
  }
}
