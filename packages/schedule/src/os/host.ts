import { execFile } from "node:child_process"
import { mkdir, readFile, realpath, rm, rmdir, writeFile } from "node:fs/promises"
import { homedir, userInfo } from "node:os"
import { basename, dirname, join, posix, win32 } from "node:path"

import type { Result } from "@vite-hub/runtime"
import type { CronFields } from "./cron.ts"
import type { OsScheduleErrorCode, OsSchedulePlatform, OsScheduleScope } from "./errors.ts"

export interface ExecResult {
  code: number
  stdout: string
  stderr: string
}

/** What the drivers need from the machine. Tests pass a fake host. */
export interface OsHost {
  platform: string
  /** `undefined` on Windows. */
  uid: number | undefined
  /** User name. On Windows `DOMAIN\user`. */
  user: string
  homedir: string
  env: Record<string, string | undefined>
  machineTimeZone: string
  now(): Date
  sleep(ms: number): Promise<void>
  exec(file: string, args: readonly string[], env?: Record<string, string>): Promise<ExecResult>
  fs: {
    /** `undefined` when the file does not exist. */
    readFile(path: string): Promise<string | undefined>
    /** Creates the parent directories. */
    writeFile(path: string, content: string): Promise<void>
    mkdir(path: string): Promise<void>
    /** Returns `true` when the file existed. */
    rm(path: string): Promise<boolean>
    rmdirIfEmpty(path: string): Promise<void>
    /** The path with every symbolic link resolved. A part that does not exist stays as it is. */
    realpath(path: string): Promise<string>
  }
}

/** One Schedule, checked, as the drivers install it. */
export interface OsTimerSpec {
  name: string
  description: string
  cron: string
  /** The cron in `timeZone`. */
  fields: CronFields
  timeZone: string
  command: readonly string[]
  env: Record<string, string>
  cwd?: string
  logDir?: string
  catchUp: boolean
  randomDelaySeconds?: number
}

export interface OsScheduleStatus {
  name: string
  platform: OsSchedulePlatform
  scope: OsScheduleScope
  /**
   * The OS knows the timer, and ViteHub installed it in this scope. `false` for a timer, unit, plist, or task of the
   * same name that ViteHub did not install: it is not this timer.
   */
  installed: boolean
  /** A run is in progress. */
  running: boolean
  /** Start of the last run. macOS does not expose it. */
  lastRunAt?: Date
  /** Exit code of the last finished run. */
  lastExitCode?: number
  /** Next time the OS starts the timer. */
  nextRunAt?: Date
  /** Linux user scope: whether systemd lingering is on. Without it, the timer runs only while the user has a session. */
  linger?: boolean
  /** File that collects the output of each run. On Linux without `logDir`, the output goes to the journal. */
  logFile?: string
}

export interface OsScheduleRemoval {
  name: string
  platform: OsSchedulePlatform
  scope: OsScheduleScope
  /** Files that the uninstall deleted. */
  removed: string[]
  /**
   * The timer or one of its files existed. `false` also when the name belongs to a timer that ViteHub did not install
   * in this scope: the uninstall leaves it as it is.
   */
  existed: boolean
}

export interface OsInstallation {
  files: string[]
  changed: boolean
  linger?: boolean
}

export interface OsDriver {
  install(spec: OsTimerSpec): Promise<Result<OsInstallation, OsScheduleErrorCode>>
  status(name: string): Promise<Result<OsScheduleStatus, OsScheduleErrorCode>>
  uninstall(name: string): Promise<Result<OsScheduleRemoval, OsScheduleErrorCode>>
}

