import { mkdir, mkdtemp, readdir, readFile, rm, writeFile } from "node:fs/promises"
import { tmpdir } from "node:os"
import { join } from "node:path"

import { resolveConfig } from "vite"
import { describe, expect, it, onTestFinished } from "vitest"

import { vitehub, type ViteHubOptions } from "../src/index.ts"
import { renderSystemdUnit, resolveSystemdUnit } from "../src/systemd.ts"

describe("renderSystemdUnit()", () => {
  it("starts the Node entry from the project root and waits for the drain budget", () => {
    const unit = resolveSystemdUnit({ drainMs: 45_000, name: "my-app", outputEntry: "/srv/my-app/.output/server/index.mjs", rootDir: "/srv/my-app/", systemd: {} })
    expect(renderSystemdUnit(unit)).toBe([
      "# Generated by ViteHub. The next build replaces this file, so customize it with a drop-in: systemctl edit my-app",
      "[Unit]",
      "Description=my-app (ViteHub)",
      "After=network-online.target",
      "Wants=network-online.target",
      "",
      "[Service]",
      "Type=simple",
      "WorkingDirectory=/srv/my-app",
      "ExecStart=/usr/bin/env node .output/server/index.mjs",
      "EnvironmentFile=-/srv/my-app/.env",
      "Environment=\"NODE_ENV=production\"",
      "SyslogIdentifier=my-app",
      "KillMode=mixed",
      "TimeoutStopSec=75",
      "Restart=on-failure",
      "RestartSec=5s",
      "",
      "[Install]",
      "WantedBy=multi-user.target default.target",
      "",
    ].join("\n"))
  })

  it("applies the deploy path, user, and environment options", () => {
    const unit = resolveSystemdUnit({
      drainMs: 0,
      name: "app",
      outputEntry: "/build/app/.output/server/index.mjs",
      rootDir: "/build/app",
      systemd: {
        environment: { GREETING: "50% \"off\"", PORT: "3000", VITEHUB_SHUTDOWN_DRAIN_MS: "60000" },
        environmentFile: "config/app.env",
        group: "app",
        user: "app",
        workingDirectory: "/srv/app",
      },
    })
    const text = renderSystemdUnit(unit)
    expect(text).toContain("User=app\nGroup=app\nWorkingDirectory=/srv/app\n")
    expect(text).toContain("EnvironmentFile=-/srv/app/config/app.env\n")
    expect(text).toContain("Environment=\"GREETING=50%% \\\"off\\\"\"\n")
    expect(text).toContain("Environment=\"PORT=3000\"\n")
    // The variable wins over the configured default at runtime, so the timeout follows it.
    expect(text).toContain("TimeoutStopSec=90\n")
  })

  it("quotes an entry path that has spaces, and reads no file with environmentFile: false", () => {
    const unit = resolveSystemdUnit({ drainMs: 0, name: "app", outputEntry: "/srv/my app/out put/server/index.mjs", rootDir: "/srv/my app", systemd: { environmentFile: false } })
    const text = renderSystemdUnit(unit)
    expect(text).toContain("WorkingDirectory=/srv/my app\n")
    expect(text).toContain("ExecStart=/usr/bin/env node \"out put/server/index.mjs\"\n")
    expect(text).not.toContain("EnvironmentFile=")
  })

  it.each([
    [{ workingDirectory: "srv/app" }, "absolute path"],
    [{ environment: { "BAD-NAME": "1" } }, "invalid variable name"],
    [{ environment: { TOKEN: "a\nb" } }, "one line"],
    [{ user: "app\nExecStartPre=/bin/false" }, "one line"],
  ])("rejects %j", (systemd, message) => {
    expect(() => resolveSystemdUnit({ drainMs: 0, name: "app", outputEntry: "/app/.output/server/index.mjs", rootDir: "/app", systemd })).toThrow(message)
  })
})

describe("vitehub({ systemd })", () => {
  interface NitroModuleHost {
    hooks: { hook(name: string, callback: (...args: unknown[]) => unknown): void }
    options: { commands: Record<string, unknown>, output: { dir: string, serverDir: string }, preset: string, rootDir: string }
  }

  /** Resolves the config and runs the Nitro `compiled` hooks of its deployment module against a fake Node build. */
  async function build(options: ViteHubOptions, command: "build" | "serve" = "build") {
    const root = await mkdtemp(join(tmpdir(), "vitehub-systemd-"))
    onTestFinished(() => rm(root, { force: true, recursive: true }))
    await writeFile(join(root, "package.json"), JSON.stringify({ name: "@acme/agent-server" }))
    const config = await resolveConfig({
      configFile: false,
      root,
      plugins: [vitehub({ blob: false, env: false, queue: false, rateLimit: false, ...options })],
    }, command)
    const modules = (config as typeof config & { nitro?: { modules?: unknown[] } }).nitro?.modules ?? []
    const outputDir = join(root, ".output")
    await mkdir(join(outputDir, "server"), { recursive: true })
    await writeFile(join(outputDir, "server/index.mjs"), "")
    const compiled: Array<() => unknown> = []
    const nitro: NitroModuleHost = {
      hooks: { hook: (name, callback) => { if (name === "compiled") compiled.push(callback as () => unknown) } },
      options: { commands: {}, output: { dir: outputDir, serverDir: join(outputDir, "server") }, preset: "node-server", rootDir: root },
    }
    // The deployment module reads only the hooks and options above.
    for (const module of modules) if (typeof module === "function") await (module as (nitro: NitroModuleHost) => unknown)(nitro)
    for (const callback of compiled) await callback()
    const services = (await readdir(outputDir)).filter(file => file.endsWith(".service"))
    return { outputDir, root, services }
  }

  it("writes a unit named after the package on the node preset", async () => {
    const { outputDir, root, services } = await build({ host: "node", agent: { shutdown: { drainMs: 20_000 } } })
    expect(services).toEqual(["acme-agent-server.service"])
    const text = await readFile(join(outputDir, services[0]!), "utf8")
    expect(text).toContain(`WorkingDirectory=${root}\n`)
    expect(text).toContain("ExecStart=/usr/bin/env node .output/server/index.mjs\n")
    expect(text).toContain("TimeoutStopSec=50\n")
  })

  it("uses systemd.name", async () => {
    const { services } = await build({ host: "node", systemd: { name: "agents" } })
    expect(services).toEqual(["agents.service"])
  })

  it("writes no unit with systemd: false, in development, or on other presets", async () => {
    expect((await build({ host: "node", systemd: false })).services).toEqual([])
    expect((await build({ host: "node" }, "serve")).services).toEqual([])
    expect((await build({ host: "vercel" })).services).toEqual([])
  })

  it("rejects an invalid unit name when it resolves the config", async () => {
    await expect(build({ host: "node", systemd: { name: "my app" } })).rejects.toThrow("systemd.name")
  })
})
