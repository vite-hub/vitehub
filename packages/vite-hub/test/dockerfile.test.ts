import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises"
import { tmpdir } from "node:os"
import { join } from "node:path"

import { resolveConfig } from "vite"
import { describe, expect, it, onTestFinished } from "vitest"

import { findNativePackages, renderDockerfile, resolveDockerfile, type BuildPlatform } from "../src/dockerfile.ts"
import { vitehub, type ViteHubOptions } from "../src/index.ts"

const linux: BuildPlatform = { arch: "x64", libc: "glibc", nodeVersion: "24.11.0", os: "linux" }

async function temporaryDir(): Promise<string> {
  const dir = await mkdtemp(join(tmpdir(), "vitehub-dockerfile-"))
  onTestFinished(() => rm(dir, { force: true, recursive: true }))
  return dir
}

describe("renderDockerfile()", () => {
  it("runs the build output as the node user, with a data volume, the health check, and the stop timeout", () => {
    const dockerfile = resolveDockerfile({ drainMs: 45_000, healthRoute: "/api/_vitehub/health", name: "my-app", nativePackages: [], platform: linux })
    expect(renderDockerfile(dockerfile)).toBe([
      "# Generated by ViteHub. The next build replaces this file. Build the image from the build output and run it:",
      "#   docker build -t my-app .output",
      "#   docker run --init --stop-timeout 75 -p 3000:3000 --env-file .env -v my-app-data:/app/.vitehub my-app",
      "# --init reaps child processes. --stop-timeout covers the Agent drain budget plus 30 seconds after SIGTERM.",
      "FROM node:24-slim",
      "WORKDIR /app",
      "COPY . .output/",
      "RUN [\"install\",\"-d\",\"-o\",\"node\",\"-g\",\"node\",\"/app\",\"/app/.vitehub\"]",
      "USER node",
      "ENV NODE_ENV=production HOST=0.0.0.0 PORT=3000",
      "EXPOSE 3000",
      "VOLUME [\"/app/.vitehub\"]",
      "STOPSIGNAL SIGTERM",
      "HEALTHCHECK --interval=30s --timeout=5s --start-period=30s --retries=3 CMD [\"node\",\"-e\",\"fetch(\\\"http://127.0.0.1:\\\" + (process.env.PORT || 3000) + \\\"/api/_vitehub/health\\\").then(r => process.exit(r.ok ? 0 : 1), () => process.exit(1))\"]",
      "CMD [\"node\",\".output/server/index.mjs\"]",
      "",
    ].join("\n"))
  })

  it("has no health check without a health route, and keeps dataDir on the volume", () => {
    const text = renderDockerfile(resolveDockerfile({ dataDir: "/var/lib/my app", drainMs: 0, name: "@Acme/Shop", nativePackages: [], platform: linux }))
    expect(text).not.toContain("HEALTHCHECK")
    expect(text).toContain("RUN [\"install\",\"-d\",\"-o\",\"node\",\"-g\",\"node\",\"/app\",\"/var/lib/my app\"]\n")
    expect(text).toContain("VOLUME [\"/var/lib/my app\"]\n")
    expect(text).toContain("#   docker run --init --stop-timeout 30 -p 3000:3000 --env-file .env -v acme-shop-data:/var/lib/my app acme-shop\n")
  })

  it("pins the CPU and C library of the build when the output has native packages", () => {
    const glibc = renderDockerfile(resolveDockerfile({ drainMs: 0, name: "app", nativePackages: ["@libsql/linux-x64-gnu"], platform: linux }))
    expect(glibc.split("\n")[0]).toBe("# check=skip=FromPlatformFlagConstDisallowed")
    expect(glibc).toContain("\nFROM --platform=linux/amd64 node:24-slim\n")
    const musl = renderDockerfile(resolveDockerfile({ drainMs: 0, name: "app", nativePackages: ["@libsql/linux-arm64-musl"], platform: { ...linux, arch: "arm64", libc: "musl" } }))
    expect(musl).toContain("\nFROM --platform=linux/arm64 node:24-alpine\n")
    // A macOS build has no Linux binaries to match, so the build warns instead.
    const darwin = renderDockerfile(resolveDockerfile({ drainMs: 0, name: "app", nativePackages: ["@libsql/darwin-arm64"], platform: { arch: "arm64", libc: undefined, nodeVersion: "22.1.0", os: "darwin" } }))
    expect(darwin).toContain("\nFROM node:22-slim\n")
    expect(darwin).not.toContain("check=skip")
  })
})

describe("findNativePackages()", () => {
  it("finds packages with os or cpu fields and compiled addons", async () => {
    const serverDir = await temporaryDir()
    const write = async (file: string, text: string) => {
      await mkdir(join(serverDir, "node_modules", file, ".."), { recursive: true })
      await writeFile(join(serverDir, "node_modules", file), text)
    }
    await write("@libsql/linux-x64-gnu/package.json", JSON.stringify({ name: "@libsql/linux-x64-gnu", cpu: ["x64"], os: ["linux"] }))
    await write("@libsql/linux-x64-gnu/index.node", "")
    await write("libsql/package.json", JSON.stringify({ name: "libsql" }))
    await write("better-sqlite3/package.json", JSON.stringify({ name: "better-sqlite3" }))
    await write("better-sqlite3/build/Release/better_sqlite3.node", "")
    await write("outer/node_modules/@scope/inner/package.json", JSON.stringify({ os: ["linux"] }))
    await write("outer/fixtures/package.json", JSON.stringify({ os: ["linux"] }))
    expect(await findNativePackages(serverDir)).toEqual(["@libsql/linux-x64-gnu", "@scope/inner", "better-sqlite3"])
  })

  it("returns no packages for a server without node_modules", async () => {
    expect(await findNativePackages(await temporaryDir())).toEqual([])
  })
})

describe("vitehub({ docker })", () => {
  interface NitroModuleHost {
    hooks: { hook(name: string, callback: (...args: unknown[]) => unknown): void }
    logger: { warn(message: string): void }
    options: { commands: Record<string, unknown>, output: { dir: string, serverDir: string }, preset: string, rootDir: string }
  }

  /** Resolves the config and runs the Nitro `compiled` hooks of its deployment module against a fake Node build. */
  async function build(options: ViteHubOptions, command: "build" | "serve" = "build") {
    const root = await temporaryDir()
    await writeFile(join(root, "package.json"), JSON.stringify({ name: "@acme/agent-server" }))
    const config = await resolveConfig({
      configFile: false,
      root,
      plugins: [vitehub({ blob: false, env: false, queue: false, rateLimit: false, systemd: false, ...options })],
    }, command)
    const modules = (config as typeof config & { nitro?: { modules?: unknown[] } }).nitro?.modules ?? []
    const outputDir = join(root, ".output")
    await mkdir(join(outputDir, "server"), { recursive: true })
    await writeFile(join(outputDir, "server/index.mjs"), "")
    const compiled: Array<() => unknown> = []
    const nitro: NitroModuleHost = {
      hooks: { hook: (name, callback) => { if (name === "compiled") compiled.push(callback as () => unknown) } },
      logger: { warn: () => {} },
      options: { commands: {}, output: { dir: outputDir, serverDir: join(outputDir, "server") }, preset: "node-server", rootDir: root },
    }
    // The deployment module reads only the hooks, the logger, and the options above.
    for (const module of modules) if (typeof module === "function") await (module as (nitro: NitroModuleHost) => unknown)(nitro)
    for (const callback of compiled) await callback()
    return readFile(join(outputDir, "Dockerfile"), "utf8").catch(() => undefined)
  }

  it("writes .output/Dockerfile on the node preset, with the health route and the drain budget", async () => {
    const text = await build({ host: "node", agent: { shutdown: { drainMs: 20_000 } }, health: { route: "/healthz" } })
    expect(text).toContain("#   docker run --init --stop-timeout 50 -p 3000:3000 --env-file .env -v acme-agent-server-data:/app/.vitehub acme-agent-server\n")
    expect(text).toContain("\\\"/healthz\\\"")
    expect(text).toContain("CMD [\"node\",\".output/server/index.mjs\"]\n")
  })

  it("writes no Dockerfile with docker: false, in development, or on other presets", async () => {
    expect(await build({ host: "node", docker: false })).toBeUndefined()
    expect(await build({ host: "node" }, "serve")).toBeUndefined()
    expect(await build({ host: "vercel" })).toBeUndefined()
  })
})
