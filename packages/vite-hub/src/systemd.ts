import { mkdir, writeFile } from "node:fs/promises"
import { dirname, join, relative, resolve } from "node:path"

import { viteHubErrorDiagnostics } from "./error-diagnostics.ts"

/** `systemd` options of `vitehub()`. */
export interface SystemdOptions {
  /** The unit name without `.service`. Defaults to the deployment name: `vitehub({ name })`, else the package.json name. */
  name?: string
  /** `User=` of a system unit. Omit it for a user unit (`systemctl --user`). */
  user?: string
  /** `Group=` of a system unit. */
  group?: string
  /**
   * Absolute app directory on the server, where the unit starts the server entry and where relative data paths resolve.
   * Defaults to the project root of the build.
   */
  workingDirectory?: string
  /** Optional environment file, relative to `workingDirectory`. Defaults to `.env`. `false` reads no file. */
  environmentFile?: string | false
  /** `Environment=` variables, such as `{ PORT: "3000" }`. */
  environment?: Record<string, string>
}

export interface SystemdUnit {
  name: string
  description: string
  drainMs: number
  entry: string
  environment: Record<string, string>
  environmentFile?: string
  group?: string
  user?: string
  workingDirectory: string
}

/** The settle and close time that ViteHub adds after the drain budget, plus 5 seconds of margin. */
const shutdownOverheadSeconds = 30
const unitName = /^[\w.:-]+$/
const variableName = /^[A-Z_a-z]\w*$/

function invalid(message: string): never {
  throw viteHubErrorDiagnostics.VITE_HUB_R0142({ message: "[vitehub] " + message })
}

/** systemd expands `%` specifiers in every value, and a line break ends the setting. */
function escapeValue(field: string, value: string): string {
  if (/[\n\r]/.test(value)) invalid(`systemd.${field} must be one line.`)
  return value.replaceAll("%", "%%")
}

/** Quotes an `ExecStart=` argument, where systemd also expands `$` variables. */
function execArgument(field: string, value: string): string {
  const escaped = escapeValue(field, value).replaceAll("$", "$$$$")
  return /^[\w./@+:,=-]+$/.test(escaped) ? escaped : `"${escaped.replaceAll("\\", "\\\\").replaceAll("\"", "\\\"")}"`
}

function quoteAssignment(name: string, value: string): string {
  return `"${escapeValue(`environment.${name}`, `${name}=${value}`).replaceAll("\\", "\\\\").replaceAll("\"", "\\\"")}"`
}

/** The stop timeout that covers the drain budget, the 15 s settle time, and the 10 s close hooks. */
export function systemdStopTimeoutSeconds(drainMs: number): number {
  return Math.ceil(drainMs / 1000) + shutdownOverheadSeconds
}

export function systemdUnitName(options: SystemdOptions, deploymentName: string): string {
  const name = options.name ?? deploymentName
  if (!unitName.test(name)) invalid(`systemd.name ${JSON.stringify(name)} may use only letters, digits, and "_.:-".`)
  return name
}

/** Resolves the unit from `vitehub({ systemd })` and the paths of the build. */
export function resolveSystemdUnit(options: {
  drainMs: number
  /** A name from `systemdUnitName()`. */
  name: string
  outputEntry: string
  rootDir: string
  systemd: SystemdOptions
}): SystemdUnit {
  const { systemd } = options
  if (systemd.workingDirectory !== undefined && !systemd.workingDirectory.startsWith("/")) invalid("systemd.workingDirectory must be an absolute path.")
  // Nitro's root ends with a slash.
  const workingDirectory = resolve(systemd.workingDirectory ?? options.rootDir)
  for (const [name, value] of Object.entries(systemd.environment ?? {})) {
    if (!variableName.test(name)) invalid(`systemd.environment has an invalid variable name ${JSON.stringify(name)}.`)
    escapeValue(`environment.${name}`, value)
  }
  for (const field of ["environmentFile", "group", "user", "workingDirectory"] as const) {
    const value = systemd[field]
    if (typeof value === "string") escapeValue(field, value)
  }
  const environmentFile = systemd.environmentFile === false ? undefined : resolve(workingDirectory, systemd.environmentFile ?? ".env")
  // The runtime reads the budget from this variable before the configured default.
  const configuredDrain = Number(systemd.environment?.VITEHUB_SHUTDOWN_DRAIN_MS)
  return {
    name: options.name,
    description: `${options.name} (ViteHub)`,
    drainMs: Number.isFinite(configuredDrain) && configuredDrain >= 0 ? configuredDrain : options.drainMs,
    entry: relative(options.rootDir, options.outputEntry).replaceAll("\\", "/"),
    environment: { NODE_ENV: "production", ...systemd.environment },
    ...(environmentFile ? { environmentFile } : {}),
    ...(systemd.group ? { group: systemd.group } : {}),
    ...(systemd.user ? { user: systemd.user } : {}),
    workingDirectory,
  }
}

export function renderSystemdUnit(unit: SystemdUnit): string {
  const lines = [
    `# Generated by ViteHub. The next build replaces this file, so customize it with a drop-in: systemctl edit ${unit.name}`,
    "[Unit]",
    `Description=${escapeValue("name", unit.description)}`,
    "After=network-online.target",
    "Wants=network-online.target",
    "",
    "[Service]",
    "Type=simple",
    ...(unit.user ? [`User=${escapeValue("user", unit.user)}`] : []),
    ...(unit.group ? [`Group=${escapeValue("group", unit.group)}`] : []),
    `WorkingDirectory=${escapeValue("workingDirectory", unit.workingDirectory)}`,
    // `env` finds `node` on the unit's PATH, so a Node.js upgrade does not leave a stale path in the unit.
    `ExecStart=/usr/bin/env node ${execArgument("entry", unit.entry)}`,
    ...(unit.environmentFile ? [`EnvironmentFile=-${escapeValue("environmentFile", unit.environmentFile)}`] : []),
    ...Object.entries(unit.environment).map(([name, value]) => `Environment=${quoteAssignment(name, value)}`),
    // Without it, the journal names the process after `env`.
    `SyslogIdentifier=${unit.name}`,
    // ViteHub drains on SIGTERM and exits once; KillMode=mixed keeps child processes alive until then.
    "KillMode=mixed",
    `TimeoutStopSec=${systemdStopTimeoutSeconds(unit.drainMs)}`,
    "Restart=on-failure",
    "RestartSec=5s",
    "",
    "[Install]",
    // multi-user.target starts a system unit at boot, default.target a user unit at login.
    "WantedBy=multi-user.target default.target",
    "",
  ]
  return lines.join("\n")
}

export async function writeSystemdUnit(outputDir: string, name: string, unit: SystemdUnit): Promise<string> {
  const file = join(outputDir, `${name}.service`)
  await mkdir(dirname(file), { recursive: true })
  await writeFile(file, renderSystemdUnit(unit), "utf8")
  return file
}
