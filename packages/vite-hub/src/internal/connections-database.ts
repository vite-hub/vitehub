import { rm } from "node:fs/promises"
import { resolve } from "node:path"

import { writeFileIfChanged } from "@vite-hub/internal/definition-catalog"

import { ownerModules } from "./owner-modules.ts"
import { requireOptionalOwner } from "./optional-owners.ts"

import type { DatabaseContributionContext, DatabaseDefinitionContribution } from "@vite-hub/database/vite"

export const connectionsDatabaseModulePath = ".vitehub/connections/database.ts"

/**
 * Connections keeps grants and activity in the `default` Database. The Vite plugin gives an app without a Database
 * Definition an empty default Database; the Nuxt Database module does not. Like the CMS and Comments, this adds the
 * `default` Database Definition when the app has none. They see it and do not add their own.
 */
export function connectionsDatabasePlugin(projectRoot: string): { name: string, vitehub: { databases: (context: DatabaseContributionContext) => Promise<DatabaseDefinitionContribution[]> } } {
  return {
    name: "vite-hub/connections-database",
    vitehub: {
      async databases(context) {
        const { discoverDatabaseDefinitions } = requireOptionalOwner(ownerModules.databaseConfig, "database")
        const module = resolve(projectRoot, connectionsDatabaseModulePath)
        if (discoverDatabaseDefinitions(context.rootDir, { serverDirs: context.serverDirs?.map(directory => resolve(projectRoot, directory)) }).length) {
          await rm(module, { force: true })
          return []
        }
        await writeFileIfChanged(module, [
          "// Generated by vite-hub for Connections. Do not edit.",
          "// The app has no Database Definition, so Connections adds the empty `default` Database for its grants and activity.",
          "// Add server/databases/config.ts to define the Database yourself.",
          "import { defineDatabase } from \"vite-hub/database\"",
          "",
          "export default defineDatabase({ schema: {} })",
          "",
        ].join("\n"))
        return [{
          definition: module,
          name: "default",
          reason: "Connections stores grants and activity in the default Database, and the app has no Database Definition. Add server/databases/config.ts to define this Database yourself.",
        }]
      },
    },
  }
}
