import { readdir, readFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { join, resolve } from "node:path";

import { expect, it } from "vitest";

import { iconShapes, lucideStroke } from "../src/internal/icon-shapes.ts";

const sourceRoot = resolve(import.meta.dirname, "../src");
const generatedShapes = join(sourceRoot, "ui-sdk/icons.ts");
const iconPattern = /\bi-(lucide|ph)-([a-z0-9]+(?:-[a-z0-9]+)*)/g;

async function sourceIcons(root: string): Promise<string[]> {
  const icons = new Set<string>();
  for (const entry of await readdir(root, { recursive: true, withFileTypes: true })) {
    if (!entry.isFile() || !/\.(?:ts|vue)$/.test(entry.name)) continue;
    // The drawn icons of the ui-sdk UIcon come from this list, so they must not keep an icon in it.
    if (join(entry.parentPath, entry.name) === generatedShapes) continue;
    const source = await readFile(join(entry.parentPath, entry.name), "utf8");
    for (const [, collection, name] of source.matchAll(iconPattern)) icons.add(`${collection}:${name}`);
  }
  return [...icons].sort();
}

it("lists every icon that the UI sources use", async () => {
  const icons = await sourceIcons(sourceRoot);
  expect(icons.length).toBeGreaterThan(0);
  await expect([
    "// Generated by test/icons.test.ts from the UI sources.",
    "// Run `vp test test/icons.test.ts -u` in packages/ui after you add or remove a UI icon.",
    "export const viteHubUIIcons: readonly string[] = [",
    ...icons.map((icon) => `  "${icon}",`),
    "];",
    "",
  ].join("\n")).toMatchFileSnapshot("../src/icons.ts");
});

it("draws every Lucide icon of the UI sources for the ui-sdk UIcon", async () => {
  const require = createRequire(import.meta.url);
  const set = JSON.parse(await readFile(require.resolve("@iconify-json/lucide/icons.json"), "utf8")) as { aliases?: Record<string, { parent: string }>, icons: Record<string, { body: string }> };
  const names = (await sourceIcons(sourceRoot)).filter(icon => icon.startsWith("lucide:")).map(icon => icon.slice("lucide:".length));
  const lines = names.map((name) => {
    // Lucide keeps renamed icons, such as `trash-2`, as aliases of the current name.
    const icon = set.icons[name] ?? set.icons[set.aliases?.[name]?.parent ?? ""];
    if (!icon) throw new Error(`The Lucide icon "${name}" does not exist.`);
    // The UIcon sets Lucide's stroke on the `<svg>`, and the shapes inherit it, so each shape keeps only what differs.
    const shapes = iconShapes(name, icon.body).map(([tag, attributes]) => [tag, Object.fromEntries(Object.entries(attributes).filter(([key, value]) => lucideStroke[key] !== value))]);
    return `  "i-lucide-${name}": ${JSON.stringify(shapes)},`;
  });
  await expect([
    "// Generated by test/icons.test.ts from the UI sources and @iconify-json/lucide.",
    "// Run `vp test test/icons.test.ts -u` in packages/ui after you add or remove a UI icon.",
    "import type { IconShapes } from \"../internal/icon-shapes.ts\";",
    "",
    "export const uiSdkIcons: Readonly<Record<string, IconShapes>> = {",
    ...lines,
    "};",
    "",
  ].join("\n")).toMatchFileSnapshot("../src/ui-sdk/icons.ts");
});
