export const EXEC_STDIO_OUTPUT_MARKER = '__VITEHUB_OUTPUT__'

export function createEntrySource(definitionPath: string, execution: 'definition' | 'module' = 'definition') {
  const invocation = execution === 'module'
    ? [
        `    const mod = await import(pathToFileURL(${JSON.stringify(definitionPath)}).href)`,
        `    const exported = await mod.default`,
        `    if (typeof exported !== 'function')`,
        `      throw new TypeError('Sandbox package entrypoint must default-export a function.')`,
        `    const result = await exported(input.payload, input.context)`,
      ]
    : [
        `    const mod = await import(pathToFileURL(${JSON.stringify(definitionPath)}).href)`,
        `    const definition = mod?.default`,
        `    if (!definition || typeof definition.run !== 'function')`,
        `      throw new Error('Sandbox Task Definition must default-export defineSandboxTask({ run }).')`,
        `    const result = await definition.run(input.payload, input.context)`,
      ]
  return [
    `import { mkdir, readFile, writeFile } from 'node:fs/promises'`,
    `import { Buffer } from 'node:buffer'`,
    `import { pathToFileURL } from 'node:url'`,
    `const serializationErrors = new WeakSet()`,
    ``,
    `function serializationError(message, cause) {`,
    `  const error = new TypeError(message, { cause })`,
    `  serializationErrors.add(error)`,
    `  return error`,
    `}`,
    ``,
    `function normalizeError(error) {`,
    `  if (error instanceof Error) {`,
    `    return {`,
    `      code: serializationErrors.has(error) ? 'SANDBOX_TASK_SERIALIZATION_ERROR' : undefined,`,
    `      name: error.name,`,
    `      message: error.message,`,
    `      stack: error.stack,`,
    `      cause: error.cause ? String(error.cause) : undefined,`,
    `    }`,
    `  }`,
    `  return {`,
    `    code: undefined,`,
    `    name: 'Error',`,
    `    message: String(error),`,
    `  }`,
    `}`,
    ``,
    `const valueMarker = ${JSON.stringify('vitehub:sandbox-task:value')}`,
    `const nativeResponseClone = typeof Response !== 'undefined' ? Response.prototype.clone : undefined`,
    `const nativeResponseBody = typeof Response !== 'undefined' ? Object.getOwnPropertyDescriptor(Response.prototype, 'body')?.get : undefined`,
    ``,
    `function isPlainObject(value) {`,
    `  if (!value || typeof value !== 'object') return false`,
    `  const prototype = Object.getPrototypeOf(value)`,
    `  return prototype === Object.prototype || prototype === null`,
    `}`,
    ``,
    `function hasMarker(value) {`,
    `  return Object.prototype.hasOwnProperty.call(value, valueMarker)`,
    `}`,
    ``,
    `const typedArrayTagGetter = Object.getOwnPropertyDescriptor(Object.getPrototypeOf(Uint8Array.prototype), Symbol.toStringTag)?.get`,
    ``,
    `function isUint8Array(value) {`,
    `  return ArrayBuffer.isView(value) && typedArrayTagGetter?.call(value) === 'Uint8Array'`,
    `}`,
    ``,
    `function unboxJsonPrimitive(value) {`,
    `  for (const unbox of [Boolean.prototype.valueOf, Number.prototype.valueOf, String.prototype.valueOf, BigInt.prototype.valueOf]) {`,
    `    try { Reflect.apply(unbox, value, []) }`,
    `    catch { continue }`,
    `    return { value: Reflect.apply(value.valueOf, value, []) }`,
    `  }`,
    `  return undefined`,
    `}`,
    ``,
    `function hasEnumerableProperties(value) {`,
    `  if (Object.keys(value).length > 0) return true`,
    `  const enumerableSymbols = Object.getOwnPropertySymbols(value).filter(symbol => Object.prototype.propertyIsEnumerable.call(value, symbol))`,
    `  if (enumerableSymbols.length === 0) return false`,
    // Enumerable symbols are user data by default. Undici's Response has two`,
    // internal symbols, but isResponse() applies an additional brand operation`,
    // before accepting that implementation-specific shape.`,
    `  return true`,
    `}`,
    ``,
    `function isResponse(value) {`,
    `  if (!value || typeof value !== 'object') return false`,
    `  try {`,
    `    let clone = nativeResponseClone`,
    `    let cloneSucceeded = false`,
    `    let cloneResult`,
    `    let bodySucceeded = false`,
    `    if (typeof clone === 'function') { try { cloneResult = clone.call(value); cloneSucceeded = true } catch {} }`,
    `    if (!cloneSucceeded && typeof nativeResponseBody === 'function') { try { nativeResponseBody.call(value); bodySucceeded = true } catch {} }`,
    `    if (cloneSucceeded || bodySucceeded) {`,
    `      return Number.isInteger(value.status) && value.status >= 0 && value.status <= 599`,
    `        && typeof value.statusText === 'string'`,
    `        && typeof value.arrayBuffer === 'function'`,
    `        && value.headers && typeof value.headers.get === 'function'`,
    `        && typeof value.headers[Symbol.iterator] === 'function'`,
    `    }`,
    `    clone = undefined`,
    `    let foreignCloneDescriptor`,
    `    let foreignBodyDescriptor`,
    `    let foreignConstructorDescriptor`,
    `    let foreignClonePrototype`,
    `    let foreignBodyPrototype`,
    `    let foreignConstructorPrototype`,
    `    let prototype = Object.getPrototypeOf(value)`,
    `    while (prototype) {`,
    `      if (typeof clone !== 'function') {`,
    `        const cloneDescriptor = Object.getOwnPropertyDescriptor(prototype, 'clone')`,
    `        if (typeof cloneDescriptor?.value === 'function') {`,
    `          clone = cloneDescriptor.value`,
    `          foreignCloneDescriptor = cloneDescriptor`,
    `          foreignClonePrototype = prototype`,
    `        }`,
    `      }`,
    `      if (!bodySucceeded) {`,
    `        const bodyDescriptor = Object.getOwnPropertyDescriptor(prototype, 'body')`,
    `        if (typeof bodyDescriptor?.get === 'function') {`,
    `          foreignBodyDescriptor = bodyDescriptor`,
    `          foreignBodyPrototype = prototype`,
    `          try { bodyDescriptor.get.call(value); bodySucceeded = true } catch {}`,
    `        }`,
    `      }`,
    `      if (!foreignConstructorDescriptor) {`,
    `        const constructorDescriptor = Object.getOwnPropertyDescriptor(prototype, 'constructor')`,
    `        if (typeof constructorDescriptor?.value === 'function') { foreignConstructorDescriptor = constructorDescriptor; foreignConstructorPrototype = prototype }`,
    `      }`,
    `      prototype = Object.getPrototypeOf(prototype)`,
    `    }`,
    `    if (!cloneSucceeded && typeof clone === 'function') { try { cloneResult = clone.call(value); cloneSucceeded = true } catch {} }`,
    `    // Consumed or locked foreign Responses reject clone(), but their branded body getter still succeeds.`,
    `    if (!bodySucceeded || typeof clone !== 'function') return false`,
    `    let cloneResultBodySucceeded = false`,
    `    if (cloneResult && cloneResult !== value && foreignBodyDescriptor) {`,
    `      try {`,
    `        const cloneResultBody = foreignBodyDescriptor.get.call(cloneResult)`,
    `        cloneResultBodySucceeded = cloneResultBody === null || (cloneResultBody && typeof cloneResultBody.getReader === 'function')`,
    `      } catch {}`,
    `    }`,
    `    const cloneResultLooksLikeResponse = Boolean(cloneResult && Number.isInteger(cloneResult.status) && cloneResult.status >= 0 && cloneResult.status <= 599 && typeof cloneResult.statusText === 'string' && typeof cloneResult.arrayBuffer === 'function' && cloneResult.headers && typeof cloneResult.headers.get === 'function' && typeof cloneResult.headers[Symbol.iterator] === 'function')`,
    `    const hasOwnConstructor = Object.prototype.hasOwnProperty.call(value, 'constructor')`,
    `    const foreignConstructor = hasOwnConstructor ? undefined : value.constructor`,
    `    const foreignPrototype = typeof foreignConstructor === 'function' ? foreignConstructor.prototype : undefined`,
    `    const hasForeignPrototype = Boolean(foreignPrototype && foreignPrototype !== Object.prototype && foreignPrototype.isPrototypeOf(value) && foreignPrototype.isPrototypeOf(cloneResult))`,
    `    let foreignConstructorSource = ''`,
    `    try { foreignConstructorSource = Function.prototype.toString.call(foreignConstructor) } catch {}`,
    `    // Independently branded implementations expose a class Response constructor;`,
    `    // rejecting callable/user-defined constructors keeps prototype-chain spoofs ordinary.`,
    `    const trustedForeignConstructor = ( /^class\\s+Response\\b/.test(foreignConstructorSource) || foreignConstructorSource.includes('[native code]') )`,
    `      && Object.prototype.hasOwnProperty.call(foreignConstructor, 'error') && Object.prototype.hasOwnProperty.call(foreignConstructor, 'json') && Object.prototype.hasOwnProperty.call(foreignConstructor, 'redirect')`,
    `      && typeof foreignConstructor.error === 'function' && typeof foreignConstructor.json === 'function' && typeof foreignConstructor.redirect === 'function'`,
    `    const constructorSharesResponsePrototype = foreignConstructorPrototype === foreignClonePrototype && foreignConstructorPrototype === foreignBodyPrototype`,
    `    // Prototype and constructor relationships are observable and can be forged by ordinary values.`,
    `    // Without a realm-local brand proof, keep enumerable values on the ordinary-object path.`,
    `    const enumerableSymbols = Object.getOwnPropertySymbols(value).filter(symbol => Object.prototype.propertyIsEnumerable.call(value, symbol))`,
    `    const undiciStateSymbol = enumerableSymbols.find(symbol => symbol.description === 'state')`,
    `    const undiciHeadersSymbol = enumerableSymbols.find(symbol => symbol.description === 'headers')`,
    `    const undiciState = undiciStateSymbol && value[undiciStateSymbol]`,
    `    const undiciHeaders = undiciHeadersSymbol && value[undiciHeadersSymbol]`,
    `    const cloneSymbols = cloneResult && Object.getOwnPropertySymbols(cloneResult).filter(symbol => Object.prototype.propertyIsEnumerable.call(cloneResult, symbol))`,
    `    const cloneStateSymbol = cloneSymbols?.find(symbol => symbol.description === 'state')`,
    `    const cloneHeadersSymbol = cloneSymbols?.find(symbol => symbol.description === 'headers')`,
    `    const cloneState = cloneStateSymbol && cloneResult[cloneStateSymbol]`,
    `    const cloneHeaders = cloneHeadersSymbol && cloneResult[cloneHeadersSymbol]`,
    `    const undiciInternals = enumerableSymbols.length === 2 && undiciState && typeof undiciState === 'object' && Number.isInteger(undiciState.status) && 'body' in undiciState && 'headersList' in undiciState && undiciHeaders && typeof undiciHeaders === 'object' && Object.prototype.hasOwnProperty.call(undiciHeaders, 'get') && typeof undiciHeaders.get === 'function' && cloneSymbols?.length === 2 && cloneState && typeof cloneState === 'object' && 'headersList' in cloneState && cloneHeaders && typeof cloneHeaders === 'object' && Object.prototype.hasOwnProperty.call(cloneHeaders, 'get') && typeof cloneHeaders.get === 'function'`,
    // Undici's internal symbols are enumerable, but any enumerable string field is
    // user data and must keep the ordinary-object path (the response descriptor
    // intentionally omits arbitrary fields).
    `    if (Object.keys(value).length > 0) return false`,
    `    if (hasEnumerableProperties(value) && !undiciInternals) return false`,
    `    return Number.isInteger(value.status) && value.status >= 0 && value.status <= 599`,
    `      && typeof value.statusText === 'string'`,
    `      && typeof value.arrayBuffer === 'function'`,
    `      && value.headers && typeof value.headers.get === 'function'`,
    `      && typeof value.headers[Symbol.iterator] === 'function'`,
    `  }`,
    `  catch { return false }`,
    `}`,
    ``,
    `function invalidDescriptor(label) {`,
    `  return new TypeError('Sandbox ' + label + ' contains an invalid binary sidecar descriptor.')`,
    `}`,
    ``,
    `async function reviveValue(value, assetsDir, label) {`,
    `  if (Array.isArray(value))`,
    `    return await Promise.all(value.map(entry => reviveValue(entry, assetsDir, label)))`,
    `  if (!value || typeof value !== 'object') return value`,
    `  if (!hasMarker(value)) {`,
    `    return Object.fromEntries(await Promise.all(Object.entries(value).map(async ([key, entry]) => [`,
    `      key,`,
    `      await reviveValue(entry, assetsDir, label),`,
    `    ])))`,
    `  }`,
    `  const descriptor = value[valueMarker]`,
    `  if (!isPlainObject(descriptor) || typeof descriptor.tag !== 'string')`,
    `    throw invalidDescriptor(label)`,
    `  if (descriptor.tag === 'object') {`,
    `    if (!Array.isArray(descriptor.entries) || !descriptor.entries.every(entry => Array.isArray(entry) && entry.length === 2 && typeof entry[0] === 'string'))`,
    `      throw invalidDescriptor(label)`,
    `    return Object.fromEntries(await Promise.all(descriptor.entries.map(async ([key, entry]) => [`,
    `      key,`,
    `      await reviveValue(entry, assetsDir, label),`,
    `    ])))`,
    `  }`,
    `  if (descriptor.tag !== 'binary'`,
    `    || !Number.isSafeInteger(descriptor.id)`,
    `    || Object.is(descriptor.id, -0)`,
    `    || descriptor.id < 0`,
    `    || (descriptor.kind !== 'blob' && descriptor.kind !== 'buffer' && descriptor.kind !== 'uint8array')`,
    `    || (typeof descriptor.type !== 'undefined' && typeof descriptor.type !== 'string'))`,
    `    throw invalidDescriptor(label)`,
    `  const bytes = new Uint8Array(await readFile(assetsDir + '/' + descriptor.id))`,
    `  return descriptor.kind === 'blob' ? new Blob([bytes], { type: descriptor.type || '' }) : descriptor.kind === 'buffer' ? Buffer.from(bytes) : bytes`,
    `}`,
    ``,
    `async function extractValue(value, assetsDir, state = { nextId: 0 }, ancestors = new Set(), key = '', applyToJSON = true) {`,
    `  if (isResponse(value)) {`,
    `    return { [valueMarker]: { tag: 'response', value: {`,
    `      body: { isNull: value.body === null, data: Buffer.from(await value.arrayBuffer()).toString('base64'), encoding: 'base64', mediaType: value.headers.get('content-type') || 'application/octet-stream' },`,
    `      headers: Array.from(value.headers),`,
    `      status: value.status,`,
    `      statusText: value.statusText,`,
    `      ...(value.type === 'opaqueredirect' ? { url: value.url } : {}),`,
    `      ...(['error', 'opaque', 'opaqueredirect'].includes(value.type) ? { type: value.type } : {}),`,
    `    } } }`,
    `  }`,
    `  const blob = typeof Blob !== 'undefined' && value instanceof Blob`,
    `  const buffer = Buffer.isBuffer(value)`,
    `  if (blob || isUint8Array(value)) {`,
    `    const id = state.nextId++`,
    `    state.directory ||= mkdir(assetsDir, { recursive: true })`,
    `    await state.directory`,
    `    const bytes = blob ? new Uint8Array(await value.arrayBuffer()) : value`,
    `    await writeFile(assetsDir + '/' + id, bytes)`,
    `    return { [valueMarker]: {`,
    `      id,`,
    `      kind: blob ? 'blob' : buffer ? 'buffer' : 'uint8array',`,
    `      ...(blob && value.type ? { type: value.type } : {}),`,
    `      tag: 'binary',`,
    `    } }`,
    `  }`,
    `  if (value && typeof value === 'object' && applyToJSON) {`,
    `    const toJSON = value.toJSON`,
    `    if (typeof toJSON === 'function')`,
    `      return await extractValue(Reflect.apply(toJSON, value, [key]), assetsDir, state, ancestors, key, false)`,
    `  }`,
    `  if (Array.isArray(value)) {`,
    `    if (ancestors.has(value))`,
    `      throw serializationError('Sandbox result must be JSON-serializable; cyclic value.')`,
    `    const nextAncestors = new Set(ancestors).add(value)`,
    `    return await Promise.all(value.map((entry, index) => extractValue(entry, assetsDir, state, nextAncestors, String(index))))`,
    `  }`,
    `  if (!value || typeof value !== 'object') return value`,
    `  const boxed = unboxJsonPrimitive(value)`,
    `  if (boxed) return await extractValue(boxed.value, assetsDir, state, ancestors, key, false)`,
    `  if (ancestors.has(value))`,
    `    throw serializationError('Sandbox result must be JSON-serializable; cyclic value.')`,
    `  const nextAncestors = new Set(ancestors).add(value)`,
    `  const sourceEntries = Object.entries(value).filter(([entryKey, entry]) => applyToJSON || entryKey !== 'toJSON' || typeof entry !== 'function')`,
    `  const entries = await Promise.all(sourceEntries.map(async ([entryKey, entry]) => [`,
    `    entryKey,`,
    `    await extractValue(entry, assetsDir, state, nextAncestors, entryKey),`,
    `  ]))`,
    `  return hasMarker(value) ? { [valueMarker]: { entries, tag: 'object' } } : Object.fromEntries(entries)`,
    `}`,
    ``,
    `async function serializeSuccess(result, assetsDir) {`,
    `  try {`,
    `    const encoded = await extractValue(result, assetsDir)`,
    `    return JSON.stringify({ ok: true, result: encoded }, (key, value) => {`,
    `      const type = typeof value`,
    `      if (type === 'undefined' || type === 'function' || type === 'symbol' || type === 'bigint')`,
    `        throw serializationError('Sandbox result must be JSON-serializable; unsupported ' + type + (key ? ' at "' + key + '".' : '.'))`,
    `      if (type === 'number' && !Number.isFinite(value))`,
    `        throw serializationError('Sandbox result must be JSON-serializable; non-finite number' + (key ? ' at "' + key + '".' : '.'))`,
    `      return value`,
    `    })`,
    `  }`,
    `  catch (error) {`,
    `    if (serializationErrors.has(error))`,
    `      throw error`,
    `    throw serializationError('Sandbox result must be JSON-serializable.', error)`,
    `  }`,
    `}`,
    ``,
    `export async function main(argv = process.argv.slice(2)) {`,
    `  const [inputPath, outputPath] = argv`,
    `  try {`,
    `    const raw = await readFile(inputPath, 'utf8')`,
    `    const input = await reviveValue(JSON.parse(raw || '{}'), inputPath + '.files', 'input')`,
    ...invocation,
    `    const output = await serializeSuccess(result, outputPath + '.files')`,
    `    await writeFile(outputPath, output)`,
    `    console.log('${EXEC_STDIO_OUTPUT_MARKER}' + output)`,
    `  }`,
    `  catch (error) {`,
    `    const output = JSON.stringify({ ok: false, error: normalizeError(error) })`,
    `    await writeFile(outputPath, output)`,
    `    console.error('${EXEC_STDIO_OUTPUT_MARKER}' + output)`,
    `    process.exitCode = 1`,
    `  }`,
    `}`,
    ``,
    `await main()`,
    ``,
  ].join('\n')
}
