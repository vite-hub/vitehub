// Writes app/utils/hero-figure/icons.ts with only the icons that the hero figure scenes name, such as
// "simple-icons:slack" or "lucide:lock". A scene must name each icon as one literal string, so this script finds it.
//
//   node scripts/hero-figure-icons.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const dir = fileURLToPath(new URL("../app/utils/hero-figure/", import.meta.url));
const sets = {};
const icons = {};
for (const file of readdirSync(`${dir}scenes`).sort()) {
  const source = readFileSync(`${dir}scenes/${file}`, "utf8");
  for (const [, name] of source.matchAll(/["'`]((?:simple-icons|lucide):[a-z0-9-]+)["'`]/g)) {
    const [set, id] = name.split(":");
    sets[set] ??= require(`@iconify-json/${set}/icons.json`);
    const json = sets[set];
    const icon = json.icons[id] ?? json.icons[json.aliases?.[id]?.parent];
    if (!icon) throw new Error(`${file}: no icon ${name}`);
    icons[name] = { body: icon.body, w: icon.width ?? json.width ?? 24, h: icon.height ?? json.height ?? 24 };
  }
}
const sorted = Object.fromEntries(Object.entries(icons).sort(([a], [b]) => a.localeCompare(b)));
writeFileSync(`${dir}icons.ts`, `// Generated by scripts/hero-figure-icons.mjs from @iconify-json. Do not edit.\n\nexport const HERO_ICONS: Record<string, { body: string; w: number; h: number }> = ${JSON.stringify(sorted, null, 2)};\n`);
console.log(`${Object.keys(sorted).length} icons`);
